"""Copy only explicit public assets to Vercel's CDN directory.

Never copy the repository root: it contains server code and may contain secrets.
The source assets remain in their existing locations with unchanged bytes.
"""
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parent.parent
PUBLIC_FILES = ('index.html', 'app.html', 'styles.css', 'app.css', 'workspace.css', 'app.js', 'app-ui.js', 'app-ai-documents.js', 'favicon.svg', 'vendor/MAMMOTH-LICENSE.txt', 'vendor/PDFJS-LICENSE.txt', 'vendor/mammoth.browser.min.js', 'vendor/pdf.min.mjs', 'vendor/pdf.worker.min.mjs')


def build():
    destination = ROOT / 'public'
    # public/ is generated by this script and ignored by Git.
    if destination.exists():
        shutil.rmtree(destination)
    for name in PUBLIC_FILES:
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / name, target)
    print(f'Prepared {len(PUBLIC_FILES)} unchanged browser assets.')


if __name__ == '__main__':
    build()
