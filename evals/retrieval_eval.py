"""Offline evaluation of knowledge selection: is the answer in the model's context?

For every question in the golden set, each strategy picks approved text within a
character budget. A case passes when the production citation check
(`find_approved_evidence_quote`) can find the answer sentence in the selected
text of the right source — the precondition for a verified automatic reply.

Run from the repository root:

    .venv/bin/python -m evals.retrieval_eval            # print the table
    .venv/bin/python -m evals.retrieval_eval --write    # also update the report and homepage numbers

No network, API key or database is used.
"""
import argparse
import json
from pathlib import Path

from backend.ai import find_approved_evidence_quote
from backend.retrieval import leading_selection, select_sources, strip_internal

ROOT = Path(__file__).resolve().parents[1]
GOLDEN = ROOT / "evals" / "retrieval_golden.json"
REPORT = ROOT / "docs" / "RETRIEVAL_EVAL.md"
SITE_DATA = ROOT / "frontend" / "src" / "retrieval-eval.json"
BUDGET_SHARES = (0.15, 0.25, 0.5, 0.75)
LEGACY_DOCUMENT_CAP = 5000


def load_golden(path=GOLDEN):
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    sources = [{"id": f"document:{index}", "kind": "approved_document", "title": document["title"],
                "text": "\n\n".join(document["sections"]), "cap": LEGACY_DOCUMENT_CAP}
               for index, document in enumerate(data["documents"])]
    cases = []
    for case in data["cases"]:
        owners = [source["id"] for source in sources if case["quote"] in source["text"]]
        if len(owners) != 1:
            raise ValueError(f"Golden quote must appear in exactly one document: {case['quote']!r}")
        cases.append({**case, "source_id": owners[0]})
    return sources, cases


def legacy(sources, _query, budget):
    """The previous behaviour: leading characters of each file until the budget runs out."""
    return strip_internal(leading_selection(sources, budget))


def bm25(sources, query, budget):
    return select_sources(sources, query, budget)[0]


STRATEGIES = {"Leading text (before)": legacy, "BM25 retrieval (now)": bm25}


def answer_in_context(selected, case):
    return any(source["id"] == case["source_id"] and find_approved_evidence_quote(source["text"], case["quote"])
               for source in selected)


def evaluate(sources=None, cases=None, shares=BUDGET_SHARES):
    if sources is None or cases is None:
        sources, cases = load_golden()
    corpus = sum(len(source["text"]) for source in sources)
    rows = []
    for share in shares:
        budget = int(corpus * share)
        row = {"share": share, "budget": budget, "results": {}}
        for name, strategy in STRATEGIES.items():
            hits, used, misses = 0, 0, []
            for case in cases:
                selected = strategy(sources, case["question"], budget)
                used += sum(len(source["text"]) for source in selected)
                if answer_in_context(selected, case):
                    hits += 1
                else:
                    misses.append(case["question"])
            row["results"][name] = {"recall": hits / len(cases), "hits": hits,
                                    "averageChars": round(used / len(cases)), "misses": misses}
        rows.append(row)
    return {"corpusChars": corpus, "documents": len(sources), "cases": len(cases), "rows": rows}


def render(report):
    names = list(STRATEGIES)
    lines = [
        "# Knowledge retrieval evaluation",
        "",
        "Generated by `python -m evals.retrieval_eval --write`. Do not edit by hand.",
        "",
        f"- Golden set: {report['cases']} customer questions over {report['documents']} synthetic documents "
        f"({report['corpusChars']:,} characters) in `evals/retrieval_golden.json`.",
        "- Metric: **answer-in-context recall** — the share of questions whose answer sentence is present, "
        "verbatim, in the text selected for the model. It is checked with the same function that verifies "
        "citations in production.",
        "- Budget: the share of the whole knowledge base that fits in the model context. Production has a fixed "
        "22,000-character budget, so a smaller share means a larger knowledge base.",
        "",
        "| Context budget | " + " | ".join(names) + " |",
        "| --- | " + " | ".join("---" for _ in names) + " |",
    ]
    for row in report["rows"]:
        cells = [f"{row['results'][name]['recall']:.0%} ({row['results'][name]['hits']}/{report['cases']})" for name in names]
        lines.append(f"| {row['share']:.0%} of knowledge ({row['budget']:,} chars) | " + " | ".join(cells) + " |")
    tightest = report["rows"][0]["results"][names[-1]]
    lines += ["", f"## Questions BM25 still misses at the tightest budget ({report['rows'][0]['share']:.0%})", ""]
    lines += [f"- {question}" for question in tightest["misses"]] or ["- None."]
    lines += [
        "",
        "## Limits of this evaluation",
        "",
        "- The documents and questions are synthetic and written for this test; real knowledge bases will differ.",
        "- BM25 matches words, not meaning. Questions phrased with entirely different vocabulary than the source "
        "can be missed; semantic (embedding) retrieval is the natural next step and can be measured with this same set.",
        "- This measures retrieval only. Whether the model then answers correctly is covered by the in-app training simulator.",
        "",
    ]
    return "\n".join(lines)


def site_data(report):
    """Compact numbers for the homepage chart; a test keeps this file in sync with the evaluation."""
    before, now = list(STRATEGIES)
    return {"cases": report["cases"], "documents": report["documents"],
            "rows": [{"share": round(row["share"] * 100), "before": round(row["results"][before]["recall"] * 100),
                      "now": round(row["results"][now]["recall"] * 100)} for row in report["rows"]]}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="update docs/RETRIEVAL_EVAL.md")
    arguments = parser.parse_args()
    report = evaluate()
    text = render(report)
    print(text)
    if arguments.write:
        REPORT.write_text(text, encoding="utf-8")
        SITE_DATA.write_text(json.dumps(site_data(report), indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
